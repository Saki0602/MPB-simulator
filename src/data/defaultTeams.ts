export const getDefaultTeams = (count = 12, structure: LeagueStructure = 'two_league'): Team[] => {
  const selectedConfigs = ALL_MPB_TEAMS_CONFIG.slice(0, count);

  const teams: Team[] = selectedConfigs.map((tDef, idx) => {
    let assignedLeague = tDef.leagueId;
    let assignedLeagueName = tDef.leagueName;

    if (structure === 'single') {
      assignedLeague = 'single';
      assignedLeagueName = 'MPBロイヤルペナント';
    } else if (structure === 'two_league') {
      const isRoyal = idx < 6;
      assignedLeague = isRoyal ? 'royal' : 'kingdom';
      assignedLeagueName = isRoyal ? 'ロイヤルリーグ' : 'キングダムリーグ';
    }

    const teamPlayers: Player[] = [];

    // Add 14 pitchers
    tDef.pitchers.forEach((p: any, pIdx: number) => {
      teamPlayers.push(createPlayer({
        id: tDef.id + '_p' + (pIdx + 1),
        teamId: tDef.id,
        name: p.name,
        number: p.number,
        age: 26,
        isPitcher: true,
        mainPosition: 'P',
        pitcherRole: p.role as PitcherRole,
        throws: (p.throws || 'R') as Hand,
        pitchVelocity: p.vel,
        control: p.ctrl,
        stamina: p.sta,
        strikeout: p.so,
        hrAvoidance: p.hr,
        winLuck: p.winLuck || 50,
        usagePolicy: (p.policy || 'normal') as any,
      }));
    });

    // Add 16 batters
    tDef.batters.forEach((b: any, bIdx: number) => {
      teamPlayers.push(createPlayer({
        id: tDef.id + '_b' + (bIdx + 1),
        teamId: tDef.id,
        name: b.name,
        number: b.number,
        age: 27,
        isPitcher: false,
        mainPosition: b.pos as Position,
        bats: (b.bats || 'R') as BatHand,
        contact: b.hit,
        power: b.pow,
        speed: b.spd || 65,
        arm: b.arm,
        fielding: b.fld,
        catching: b.fld,
        eye: b.eye,
        usagePolicy: (b.policy || 'normal') as any,
      }));
    });

    const teamObj: Team = {
      id: tDef.id,
      name: tDef.name,
      shortName: tDef.shortName,
      city: tDef.city,
      stadium: tDef.stadium,
      color: tDef.color,
      secondaryColor: tDef.secondaryColor,
      textColor: tDef.textColor,
      leagueId: assignedLeague,
      leagueName: assignedLeagueName,
      stats: {
        games: 0, wins: 0, losses: 0, draws: 0, winRate: 0, gamesBehind: 0,
        runsScored: 0, runsAllowed: 0, runDiff: 0, streak: '-', rank: idx + 1
      },
      order: {
        battingOrder: [],
        rotation: [],
        relievers: [],
        setup: '',
        closer: '',
        benchBatters: [],
        bullpenPitchers: []
      },
      players: teamPlayers,
    };

    teamObj.order = AIManager.generateBestOrder(teamObj);
    return teamObj;
  });

  return teams;
};
