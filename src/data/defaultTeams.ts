export const createPlayer = (p: Partial<Player> & {
  id: string;
  teamId: string;
  name: string;
  number: number;
  age: number;
  isPitcher: boolean;
  mainPosition: Position;
}): Player => {
  const isP = p.isPitcher;
  const defAptitudes: Record<Position, number> = {
    P: isP ? 90 : 10,
    C: p.mainPosition === 'C' ? 85 : 10,
    '1B': p.mainPosition === '1B' ? 85 : 30,
    '2B': p.mainPosition === '2B' ? 85 : 25,
    '3B': p.mainPosition === '3B' ? 85 : 25,
    SS: p.mainPosition === 'SS' ? 85 : 20,
    LF: p.mainPosition === 'LF' ? 85 : 30,
    CF: p.mainPosition === 'CF' ? 85 : 30,
    RF: p.mainPosition === 'RF' ? 85 : 30,
    DH: 90,
    ...(p.positionAptitudes || {}),
  };

  return {
    id: p.id,
    teamId: p.teamId,
    name: p.name,
    number: p.number,
    age: p.age,
    isPitcher: isP,
    bats: p.bats || 'R',
    throws: p.throws || 'R',
    mainPosition: p.mainPosition,
    positionAptitudes: defAptitudes,
    contact: p.contact ?? (isP ? 25 : 65),
    power: p.power ?? (isP ? 20 : 65),
    speed: p.speed ?? (isP ? 40 : 65),
    arm: p.arm ?? (isP ? 60 : 65),
    fielding: p.fielding ?? (isP ? 55 : 65),
    catching: p.catching ?? (isP ? 50 : 65),
    eye: p.eye ?? (isP ? 30 : 65),
    stealing: p.stealing ?? (isP ? 20 : 55),
    vsRight: p.vsRight ?? 65,
    vsLeft: p.vsLeft ?? 65,
    pitcherRole: p.pitcherRole || (isP ? 'starter' : 'reliever'),
    pitchVelocity: p.pitchVelocity ?? (isP ? 146 : 130),
    control: p.control ?? (isP ? 65 : 40),
    stamina: p.stamina ?? (isP ? (p.pitcherRole === 'starter' ? 75 : 45) : 30),
    strikeout: p.strikeout ?? (isP ? 65 : 30),
    hrAvoidance: p.hrAvoidance ?? (isP ? 65 : 40),
    pVsRight: p.pVsRight ?? 65,
    pVsLeft: p.pVsLeft ?? 65,
    winLuck: p.winLuck ?? (isP ? 50 : 50),
    pitches: p.pitches || (isP ? [
      { id: '1', name: 'ストレート', velocity: p.pitchVelocity ?? 146, breakAmount: 30, ballPower: 70, control: 70 },
      { id: '2', name: 'スライダー', velocity: (p.pitchVelocity ?? 146) - 14, breakAmount: 70, ballPower: 65, control: 65 },
      { id: '3', name: 'フォーク', velocity: (p.pitchVelocity ?? 146) - 15, breakAmount: 65, ballPower: 65, control: 60 },
    ] : []),
    condition: '普通',
    fatigue: 0,
    recentForm: [0, 0, 0],
    batterStats: emptyBatterStats(),
    pitcherStats: emptyPitcherStats(),
    usagePolicy: p.usagePolicy || 'normal',
  };
};

